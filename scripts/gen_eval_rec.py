#!/usr/bin/env python3
"""Generate the recursive driver of `eval` (src/eval/mod.rs) from `combine` and `descend`

`eval_rec` matches a node once: a two-operand node evaluates its operands and applies the law
function `combine` applies to that kind; a translation moves the point; every other one-child node
of `descend` moves it and finishes through `descend` / `finish`; the rest are leaves (`eval_leaf`).
Each arm's work is a function of its own, inlined in an optimised build (one dispatch per node)
and called in an unoptimised one (so `eval_rec`'s frame holds the match, not every arm's values).

The arms are read from the source of `combine` and `descend`, so a law is written once: this file
writes the block between the markers and `--check` fails when the block is not what the source
gives (or when it found no arm). `src/walker_drivers_tests.rs` checks the same correspondence from
the Rust side.

Usage: scripts/gen_eval_rec.py [--check]

Author: Moroya Sakamoto
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

SRC = Path(__file__).resolve().parent.parent / "src" / "eval" / "mod.rs"
TYPES = Path(__file__).resolve().parent.parent / "src" / "types" / "mod.rs"  # the enum
BEGIN = "// BEGIN generated by scripts/gen_eval_rec.py (do not edit)"
END = "// END generated by scripts/gen_eval_rec.py"


def body_of(text: str, signature: str) -> str:
    start = text.index(signature)
    return text[start : text.index("\n}\n", start)]


def two_operand_arms(text: str) -> list[tuple[str, str, str, str]]:
    """(kind, field pattern, law function, extra arguments) for each law arm of `combine`"""
    body = body_of(text, "fn combine(node: &SdfNode, d1: f32, d2: f32, point: Vec3) -> f32 {")
    arms = re.findall(
        r"^        SdfNode::([A-Za-z0-9]+) \{([^}]*)\} => ((?:sdf_[a-z0-9_]+|smooth_blend))\(d1, d2((?:, [^)]*)?)\),$",
        body,
        re.M,
    )
    return [(k, " ".join(f.split()).rstrip(", ").strip(), fn, rest) for k, f, fn, rest in arms]


def combine_kinds(text: str) -> list[str]:
    """every kind `combine` matches (the law arms and the ones with a body, e.g. MetricBlend)"""
    body = body_of(text, "fn combine(node: &SdfNode, d1: f32, d2: f32, point: Vec3) -> f32 {")
    return re.findall(r"^        SdfNode::([A-Za-z0-9]+) \{", body, re.M)


def one_child_kinds(text: str) -> list[str]:
    """the kinds `descend` gives one child, in order (every arm after the first one-child arm, without
    its arm for the leaves, which it hands to `eval_leaf`)"""
    body = body_of(text, "fn descend(node: &SdfNode, point: Vec3) -> Step<'_> {")
    at = body.index("SdfNode::Translate {")
    tail = body[body.rindex("\n", 0, at) + 1 :]
    tail = re.sub(
        r"(?:\s*\|?\s*SdfNode::[A-Za-z0-9]+ \{ \.\. \})+\s*=> Step::Leaf\(eval_leaf\(", "", tail
    )
    seen: list[str] = []
    for name in re.findall(r"^\s+(?:\| )?SdfNode::([A-Za-z0-9]+)", tail, re.M):
        if name not in seen:
            seen.append(name)
    return seen


def declared_kinds() -> list[str]:
    """the variants of `SdfNode`, in declaration order, read from its source"""
    src = TYPES.read_text(encoding="utf-8")
    start = src.index("pub enum SdfNode {")
    body = src[start : src.index("\n}\n", start)]
    return re.findall(r"^    ([A-Z][A-Za-z0-9_]*)(?: \{|\(|,)", body, re.M)


def field_types(kind: str) -> dict[str, str]:
    """the fields of `SdfNode::<kind>` and their types, read from the enum (`Self` as `SdfNode`)"""
    src = TYPES.read_text(encoding="utf-8")
    start = src.index("pub enum SdfNode {")
    enum = src[start : src.index("\n}\n", start)]
    m = re.search(rf"^    {kind} \{{\n(.*?)^    \}},", enum, re.M | re.S)
    if not m:
        raise SystemExit(f"gen_eval_rec: no struct variant {kind} in {TYPES}")
    fields = re.findall(r"^        ([a-z_][a-z0-9_]*): (.+),$", m.group(1), re.M)
    return {name: ty.replace("Self", "SdfNode") for name, ty in fields}


def leaf_kinds(text: str) -> list[str]:
    """the kinds `eval_leaf` has an arm for, without its arm for the kinds with children (that arm
    returns `f32::MAX` and is never reached: `descend` handles those kinds)"""
    body = body_of(text, "fn eval_leaf(node: &SdfNode, point: Vec3) -> f32 {")
    body = re.sub(r"(?:\s*\|?\s*SdfNode::[A-Za-z0-9]+ \{ \.\. \})+\s*=> f32::MAX", "", body)
    seen: list[str] = []
    for name in re.findall(r"SdfNode::([A-Za-z0-9]+)", body):
        if name not in seen:
            seen.append(name)
    return seen


def coverage(text: str) -> tuple[int, list[str]]:
    """(kinds compared, problems): every variant of the enum is a two-operand kind of `combine`, a
    one-child kind of `descend` or a leaf of `eval_leaf`, exactly one of them"""
    groups = {
        "two-operand": [t[0] for t in two_operand_arms(text)] + ["MetricBlend"],
        "one-child": one_child_kinds(text),
        "leaf": leaf_kinds(text),
    }
    problems = []
    declared = declared_kinds()
    for kind in declared:
        where = [g for g, kinds in groups.items() if kind in kinds]
        if len(where) != 1:
            problems.append(f"SdfNode::{kind}: in {where or 'no group'} (eval_rec needs exactly one)")
    for g, kinds in groups.items():
        for kind in kinds:
            if kind not in declared:
                problems.append(f"SdfNode::{kind} ({g}) is not a variant of the enum")
    return len(declared), problems


def snake(name: str) -> str:
    s = re.sub(r"(?<=[a-z0-9])([A-Z])", r"_\1", name)
    s = re.sub(r"(?<=[A-Z])([A-Z][a-z])", r"_\1", s)
    return s.lower()


INLINE = "#[cfg_attr(not(debug_assertions), inline(always))]"


def extras(fields: str) -> list[str]:
    """the fields a law arm of `combine` binds besides its operands"""
    return [f.strip() for f in fields.split(",") if f.strip() not in ("", "..")]


def generate(text: str) -> str:
    two = two_operand_arms(text)
    kinds = combine_kinds(text)
    ones = one_child_kinds(text)
    if not two or not ones:
        raise SystemExit("gen_eval_rec: no arm found in combine or descend")
    others = [k for k in kinds if k not in {t[0] for t in two}]
    if others != ["MetricBlend"]:
        raise SystemExit(f"gen_eval_rec: combine has arms this generator does not know: {others}")
    if ones[0] != "Translate":
        raise SystemExit("gen_eval_rec: descend's first one-child arm is not Translate")
    out = [BEGIN, ""]
    out.append(
        "/// `node` at `point`, `depth` levels below the root: native recursion for the first\n"
        "/// `native_levels` levels, the work-stack loop below that. One match per node: a two-operand\n"
        "/// node evaluates its operands (in order) and applies the law function [`combine`] applies to\n"
        "/// its kind, a translation moves the point, the other one-child nodes go through [`descend`] and\n"
        "/// [`finish`], the rest are leaves ([`eval_leaf`]); `native_levels` is `EVAL_NATIVE_LEVELS`\n"
        "/// except in the test that runs both drivers alone"
    )
    out.append(
        "pub(crate) fn eval_rec(node: &SdfNode, point: Vec3, depth: u32, native_levels: u32) -> f32 {"
    )
    out.append("    if depth >= native_levels {")
    out.append("        return eval_iter(node, point);")
    out.append("    }")
    out.append("    let at = Below {")
    out.append("        point,")
    out.append("        next: depth + 1,")
    out.append("        native_levels,")
    out.append("    };")
    out.append("    match node {")
    for kind, fields, _, _ in two:
        extra = extras(fields)
        args = "".join(f"*{f}, " for f in extra)
        pat = ", ".join(["a", "b", *extra, ".."])
        out.append(
            f"        SdfNode::{kind} {{ {pat} }} => rec_{snake(kind)}(a, b, {args}at),"
        )
    out.append(
        "        SdfNode::MetricBlend { inner, outer, .. } => "
        "rec_metric_blend(node, inner, outer, at),"
    )
    out.append(
        "        SdfNode::Translate { child, offset } => rec_translate(child, *offset, at),"
    )
    pattern = "\n        | ".join(f"SdfNode::{k} {{ .. }}" for k in ones[1:])
    out.append(f"        {pattern} => rec_one(node, at),")
    out.append("        _ => eval_leaf(node, point),")
    out.append("    }")
    out.append("}")
    out += [
        "",
        "/// Where [`eval_rec`] is in the walk: the point, the depth of the children and the native limit",
        "#[derive(Clone, Copy)]",
        "struct Below {",
        "    point: Vec3,",
        "    next: u32,",
        "    native_levels: u32,",
        "}",
        "",
        "/// [`eval_rec`] of `node` at `at` (one level below the node that holds it)",
        INLINE,
        "fn rec(node: &SdfNode, at: Below) -> f32 {",
        "    eval_rec(node, at.point, at.next, at.native_levels)",
        "}",
    ]
    for kind, fields, fn, rest in two:
        extra = extras(fields)
        types = field_types(kind) if extra else {}
        params = "".join(f"{f}: {types[f]}, " for f in extra)
        out.append("")
        out.append(f"/// [`eval_rec`] at a `{kind}` (its operands and fields): both operands, then `{fn}`")
        out.append(INLINE)
        out.append(f"fn rec_{snake(kind)}(a: &SdfNode, b: &SdfNode, {params}at: Below) -> f32 {{")
        out.append(f"    {fn}(rec(a, at), rec(b, at){rest.replace('*', '')})")
        out.append("}")
    out += [
        "",
        "/// [`eval_rec`] at a `MetricBlend` (`node`, its `inner` and `outer`): both, then its law in",
        "/// [`combine`]",
        INLINE,
        "fn rec_metric_blend(node: &SdfNode, inner: &SdfNode, outer: &SdfNode, at: Below) -> f32 {",
        "    combine(node, rec(inner, at), rec(outer, at), at.point)",
        "}",
        "",
        "/// [`eval_rec`] at a `Translate` (its `child` and `offset`): the child at the moved point (the",
        "/// move of [`descend`])",
        INLINE,
        "fn rec_translate(child: &SdfNode, offset: Vec3, at: Below) -> f32 {",
        "    rec(",
        "        child,",
        "        Below {",
        "            point: transform_translate(at.point, offset),",
        "            ..at",
        "        },",
        "    )",
        "}",
        "",
        "/// [`eval_rec`] at another one-child node: [`descend`] moves the point, [`finish`] applies the law (or",
        "/// [`descend`] gives the node's value without its child)",
        INLINE,
        "fn rec_one(node: &SdfNode, at: Below) -> f32 {",
        "    match descend(node, at.point) {",
        "        Step::One(child, q, extra) => {",
        "            finish(node, rec(child, Below { point: q, ..at }), at.point, extra)",
        "        }",
        "        // a one-child kind may give its value without reading the child",
        "        Step::Leaf(d) => d,",
        "        // `eval_rec` sends no two-operand kind here; the arm keeps the walk total",
        "        Step::Two(a, b) => combine(node, rec(a, at), rec(b, at), at.point),",
        "    }",
        "}",
        "",
        END,
    ]
    return "\n".join(out)


def rustfmt(text: str) -> str:
    """the file as `cargo fmt` writes it (the repository's rustfmt settings and edition)"""
    out = subprocess.run(
        ["rustfmt", "--edition", "2021", "--emit", "stdout"],
        input=text,
        capture_output=True,
        text=True,
        cwd=SRC.parent.parent.parent,
        check=True,
    ).stdout
    if not out.strip():
        raise SystemExit("gen_eval_rec: rustfmt returned nothing")
    return out


def main(argv: list[str]) -> int:
    check = argv[1:] == ["--check"]
    if argv[1:] not in ([], ["--check"]):
        print(__doc__)
        return 2
    text = SRC.read_text(encoding="utf-8")
    compared, problems = coverage(text)
    if compared == 0:
        print(f"gen_eval_rec: no variant of SdfNode read from {TYPES}")
        return 1
    block = generate(text)
    if BEGIN in text:
        a = text.index(BEGIN)
        b = text.index(END, a) + len(END)
        new = rustfmt(text[:a] + block + text[b:])
    else:
        raise SystemExit(f"gen_eval_rec: no `{BEGIN}` marker in {SRC}")
    if problems:
        print("gen_eval_rec: " + "\n  ".join([f"{len(problems)} kind(s) not covered:"] + problems))
        return 1
    if check:
        if new != text:
            print(f"gen_eval_rec: {SRC} is not what the generator writes; run scripts/gen_eval_rec.py")
            return 1
        print(
            f"gen_eval_rec: ok ({compared} kinds: {len(two_operand_arms(text)) + 1} two-operand, "
            f"{len(one_child_kinds(text))} one-child, the rest leaves)"
        )
        return 0
    SRC.write_text(new, encoding="utf-8")
    print(f"gen_eval_rec: wrote {SRC}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
