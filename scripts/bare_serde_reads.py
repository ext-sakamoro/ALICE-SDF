#!/usr/bin/env python3
"""ALICE-Law G8: every bare read of a stored form in library code is a reviewed site.

The SDF tree types keep `Deserialize` (a type's field layout, which every serde user of the
types relies on), so a bare `serde_json` / bincode read of a tree would skip the stored
semantics identifier. The library clippy configuration (`.github/clippy-lib/clippy.toml`,
generated by `scripts/clippy_lib_gate.py`) forbids those entry points; clippy matches the
resolved path, so an alias, a brace import or a re-export is found as well. A reviewed site
carries

    #[allow(clippy::disallowed_methods, reason = "stored form <status>: <why>")]

on the statement or the function, where `<status>` is

* `checked`: the identifier is checked (sdf_load_verdict) before the value is returned
* `other-type`: the value read is not an SDF tree or a value computed under the SDF
  arithmetic (the reason names the type)
* `pending`: a reader that still has to check (the reason names the group)

It is an `allow`, not an `expect`: the root configuration (tests, examples, `--all-targets`)
does not forbid these calls, so an `expect` would be unfulfilled there. That each site still
contains a stored-form read, and that no such read hides under another allow of the lint (one
written for libm, say), is checked by `scripts/clippy_lib_hidden_check.py`, which lifts every
allow in a scratch copy and uses `sites()` from here. This script lists the sites, and fails
on a site with an unknown status or a reason under 12 characters, on an `expect` (unfulfilled
under the root configuration), and when it found no site or no source file.

usage: bare_serde_reads.py [--root DIR]
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

LINT = "clippy::disallowed_methods"
ATTR = re.compile(r"#\[(?P<kind>expect|allow)\(\s*" + re.escape(LINT)
                  + r'\s*,\s*reason\s*=\s*"stored form (?P<reason>(?:[^"\\]|\\.)*)"\s*,?\s*\)\]', re.S)
STATUSES = ("checked", "other-type", "pending")
OPEN, CLOSE = "([{", ")]}"


def item_end(text: str, start: int) -> int:
    """Offset just past the statement or item that begins at `start`: the first `;` at depth
    0, or the `}` that closes a block opened at depth 0 (string literals skipped)"""
    depth, i, opened = 0, start, False
    while i < len(text):
        c = text[i]
        if c == '"':
            i += 1
            while i < len(text) and text[i] != '"':
                i += 2 if text[i] == "\\" else 1
        elif c == "/" and text.startswith("//", i):
            i = text.find("\n", i)
            if i < 0:
                return len(text)
            continue
        elif c in OPEN:
            depth += 1
            opened = opened or c == "{"
        elif c in CLOSE:
            depth -= 1
            if depth == 0 and c == "}" and opened:
                return i + 1
        elif c == ";" and depth == 0:
            return i + 1
        i += 1
    return len(text)


def sites(text: str) -> list[dict]:
    """Each stored-form attribute: kind, status, why, and the 1-based line range it covers
    (from the attribute to the end of the statement or item it is on)"""
    out = []
    for m in ATTR.finditer(text):
        status, _, why = m["reason"].partition(":")
        end = item_end(text, m.end())
        out.append({"kind": m["kind"], "status": status.strip(), "why": why.strip(),
                    "first": text.count("\n", 0, m.start()) + 1, "last": text.count("\n", 0, end) + 1})
    return out


def scan(root: Path) -> tuple[int, list[tuple[str, dict]]]:
    files = sorted((root / "src").rglob("*.rs"))
    found = []
    for p in files:
        rel = p.relative_to(root).as_posix()
        found += [(rel, s) for s in sites(p.read_text(encoding="utf-8"))]
    return len(files), found


def problems_of(found: list[tuple[str, dict]]) -> list[str]:
    out = []
    for rel, s in found:
        where = f"{rel}:{s['first']}"
        if s["kind"] != "allow":
            out.append(f"{where}: a stored-form site uses expect, which the root configuration leaves unfulfilled; "
                       "use allow (scripts/clippy_lib_hidden_check.py checks the site still reads)")
        if s["status"] not in STATUSES:
            out.append(f"{where}: status must be one of {STATUSES}, got {s['status']!r}")
        if len(s["why"]) < 12:
            out.append(f"{where}: the reason must say why (12 characters or more after the status)")
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--root", default=str(Path(__file__).resolve().parents[1]))
    args = ap.parse_args(argv)
    root = Path(args.root)
    files, found = scan(root)
    if files == 0:
        print(f"bare_serde_reads: FAIL: no source file under {root / 'src'} (0 scanned)")
        return 1
    if not found:
        print(f"bare_serde_reads: FAIL: no stored-form site under {root / 'src'} (compared nothing)")
        return 1
    problems = problems_of(found)
    by = {s: sum(1 for _, x in found if x["status"] == s) for s in STATUSES}
    print(f"bare_serde_reads: {files} files scanned; {len(found)} stored-form sites ("
          + ", ".join(f"{by[s]} {s}" for s in STATUSES) + f", {len(problems)} problems)")
    for rel, s in found:
        print(f"  {s['status']:<10} {rel}:{s['first']}-{s['last']}  {s['why']}")
    for p in problems:
        print("  error: " + p)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
